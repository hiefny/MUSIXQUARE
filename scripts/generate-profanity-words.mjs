#!/usr/bin/env node
/** Generate the compact runtime profanity list from content-shield metadata. */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import { KO } from 'content-shield/languages/ko';
import { EN } from 'content-shield/languages/en';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(repoRoot, 'src/chat/profanity-words.generated.ts');

function collectWords() {
  const words = new Set();
  for (const entry of KO.profanity) {
    if (entry.severity < 2) continue;
    for (const variation of entry.variations) words.add(variation.toLowerCase());
  }
  for (const entry of EN.words) {
    if (entry.severity < 2) continue;
    words.add(entry.word.toLowerCase());
    for (const variation of entry.variations) words.add(variation.toLowerCase());
  }
  return [...words].sort((a, b) => b.length - a.length || (a < b ? -1 : a > b ? 1 : 0));
}

async function render() {
  const words = collectWords();
  const source = `/** Generated by scripts/generate-profanity-words.mjs. Do not edit. */
export const PROFANITY_WORDS = ${JSON.stringify(words)} as const;
`;
  return prettier.format(source, { parser: 'typescript', singleQuote: true, printWidth: 100 });
}

async function main() {
  const expected = await render();
  if (process.argv.includes('--check')) {
    const actual = await readFile(outputPath, 'utf8').catch(() => '');
    if (actual !== expected) {
      console.error('Generated profanity list is stale. Run: npm run profanity:generate');
      process.exitCode = 1;
      return;
    }
    console.log('Generated profanity list is current.');
    return;
  }
  await writeFile(outputPath, expected);
  console.log(`Wrote ${outputPath} (${collectWords().length} entries).`);
}

main().catch((error) => {
  console.error('Profanity-list generation failed:', error);
  process.exitCode = 1;
});
