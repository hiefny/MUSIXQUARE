export type LanguageCode = (typeof LANGUAGE_OPTIONS)[number]['code'];

const DEFAULT_LANGUAGE: LanguageCode = 'en';

const LANGUAGE_CODES = new Set<string>(LANGUAGE_OPTIONS.map(({ code }) => code));
const RTL_LANGUAGE_CODES = new Set<LanguageCode>(['ar', 'fa', 'he', 'ur']);
const LANGUAGE_ALIASES: Readonly<Record<string, LanguageCode>> = {
  in: 'id',
  iw: 'he',
  no: 'nb',
  tl: 'fil',
};

function isLanguageCode(value: unknown): value is LanguageCode {
  return typeof value === 'string' && LANGUAGE_CODES.has(value);
}

function normalizeLanguageCode(value: unknown): LanguageCode | null {
  const normalized = String(value ?? '')
    .trim()
    .replace(/_/gu, '-')
    .toLowerCase();
  if (isLanguageCode(normalized)) return normalized;
  return LANGUAGE_ALIASES[normalized] ?? null;
}

export function languageDirection(code: LanguageCode): 'ltr' | 'rtl' {
  return RTL_LANGUAGE_CODES.has(code) ? 'rtl' : 'ltr';
}

export function localizedAppPath(code: LanguageCode): string {
  return code === DEFAULT_LANGUAGE ? '/' : `/${code}/`;
}

/** User-facing locale entry. English uses `/en/` while its SEO canonical remains `/`. */
export function localizedAppEntryPath(code: LanguageCode): string {
  return `/${code}/`;
}

export function localizedAboutPath(code: LanguageCode): string {
  return code === DEFAULT_LANGUAGE ? '/about' : `/${code}/about`;
}

export function appLanguageFromPathname(pathname: string): LanguageCode | null {
  const normalized = String(pathname || '/').toLowerCase();
  const match = /^\/([^/]+)(?:\/|\/index\.html)$/u.exec(normalized);
  return normalizeLanguageCode(match?.[1]);
}
